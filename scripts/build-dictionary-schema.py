#!/usr/bin/python3
"""Build src/data/dictionarySchema.js from the project's own semantic-layer specification workbook (schema/lineage documentation — no data rows).
For every dictionary metric it keeps the lineage rows of the attributes the metric is computed from: source system, dataset, table, column, meaning, evidenced transformation, join keys,
the lineage status in the specification, and whether the schema exists. A row is «verified» ONLY when the specification marks it Business-confirmed; everything else stays «mapping not yet confirmed».
Tools and platforms (Makeen, Incorta, Databank, Balady Bayanat …) are never emitted as source systems. Usage: /usr/bin/python3 scripts/build-dictionary-schema.py [workbook.xlsx]"""
import json, os, re, sys, openpyxl
WB = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser('~/Desktop/IIM-Requirements-Handover/01_Semantic_Layer_Specification/IIM_Semantic_Layer_Specification.xlsx')
wb = openpyxl.load_workbook(WB, read_only=True)
def sheet(n):
    rows = [tuple(r) for r in wb[n].iter_rows(values_only=True) if any(x is not None for x in r)]
    h = list(rows[0]); return [dict(zip(h, r)) for r in rows[1:]]
MET = {r['id']: r for r in sheet('04_Metrics')}; LIN = sheet('05_Lineage'); SRC = {r['id']: r for r in sheet('01b_Sources')}
TOOLS = {r['id'] for r in sheet('01c_Tools_Platforms') if str(r.get('must_not_be_listed_as_source')).lower().startswith('yes')}
KEY = {'gross': 'MET-001', 'cancelled': 'MET-006', 'exclusions': 'MET-003', 'net': 'MET-007', 'collected': 'MET-008', 'uncollected': 'MET-011', 'netUncollected': 'MET-013', 'overdue': 'MET-015', 'notYetDue': 'MET-014',
       'collectedOverNet': 'MET-018', 'targetCollection': 'MET-033', 'remainingToTarget': 'MET-023', 'coverageRatio': 'MET-024', 'budgetCh13': 'MET-025'}
TERM = {'amanah': 'TERM-009', 'invoiceKey': 'TERM-004', 'dueDate': 'TERM-051', 'cutoff': 'TERM-061', 'grace': 'TERM-064'}   # glossary terms: the lineage rows of the term itself
def atts(mid, seen=()):
    out = []
    for t in re.findall(r'(ATT-ENT\d+-\d+|MET-\d+)', str(MET[mid]['inputs'] or '')):
        if t.startswith('MET-') and t in MET and t not in seen: out += atts(t, seen + (mid,))
        elif t.startswith('ATT-'): out.append(t)
    return list(dict.fromkeys(out))
def cut(s, n=230):
    s = re.sub(r'\s+', ' ', str(s or '')).strip(); return s if len(s) <= n else s[:n - 1].rstrip() + '…'
def src_names(ids):
    out = []
    for i in re.findall(r'SRC-\d+', str(ids or '')):
        if i in TOOLS or i not in SRC: continue
        nm = str(SRC[i]['name']).split(' – ')[0].split(' (')[0].strip()
        if nm not in out: out.append(nm)
    return out
def has_schema(r):
    t = str(r['table_view'] or ''); f = str(r['original_field'] or ''); d = str(r['dataset'] or '')
    return not (f.startswith('To be confirmed') or t.startswith('Not in Databank') or f.startswith('Business field name only') or d.startswith('Not in Databank') or 'to be supplied' in f.lower())
out = {}
for key, mid in list(KEY.items()) + list(TERM.items()):
    rows = []; seen = set()
    for a in (atts(mid) if mid.startswith('MET-') else [mid]):
        for r in LIN:
            if r['object_id'] != a: continue
            if 'not applicable' in str(r['availability'] or '').split('\n')[0]: continue   # produced by the application itself, not a source
            k = (r['table_view'], r['original_field'])
            if k in seen: continue
            seen.add(k)
            ok = has_schema(r); confirmed = str(r['status']) == 'Business-confirmed' and ok
            rows.append({'attribute': cut(r['object_name'], 90), 'sources': src_names(r['originating_source_ids']), 'dataset': cut(r['dataset'], 120), 'table': cut(r['table_view'], 140), 'column': cut(r['original_field'], 160),
                         'meaning': cut(r['meaning'], 150), 'transformation': cut(r['transformation_evidenced'], 170), 'join': cut(r['join_or_key'], 170), 'specStatus': str(r['status']), 'schema': ok, 'verified': confirmed,
                         'gap': cut(r['lineage_gap'], 200) if not ok else ''})
    total = len(rows)
    rows = sorted(rows, key=lambda x: (not x['schema'], x['attribute']))[:12]   # rows with a schema first; a short, readable table (the specification keeps the full lineage)
    state = 'verified' if any(x['verified'] for x in rows) else 'available' if any(x['schema'] for x in rows) else 'none'
    out[key] = {'ref': mid, 'state': state, 'total': total, 'rows': rows}
for k in ('revenueAppropriation',): out[k] = {'ref': None, 'state': 'none', 'total': 0, 'rows': []}
js = '// GENERATED by scripts/build-dictionary-schema.py from the project\'s semantic-layer specification (schema and lineage documentation; no data rows). Do not edit by hand.\n' \
     '// state: verified = a mapping the specification marks Business-confirmed · available = the schema exists but no mapping is confirmed · none = no schema is available for the source of this metric.\n' \
     'export const DICTIONARY_SCHEMA = ' + json.dumps(out, ensure_ascii=False, indent=1) + ';\n'
open('src/data/dictionarySchema.js', 'w', encoding='utf-8').write(js)
print({k: (v['state'], len(v['rows'])) for k, v in out.items()})
