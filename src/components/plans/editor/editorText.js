/** the text of a key in a language, {placeholders} filled; an unknown key returns the key itself (the parity test makes sure none is unknown) */
export function tt(key, lang = 'ar', vars = null) {
  const e = TEXT[key]; if (!e) return key;
  const s = lang === 'en' ? e.en : e.ar;
  return vars ? String(s).replace(/\{(\w+)\}/g, (m, k) => (vars[k] === undefined || vars[k] === null ? '' : String(vars[k]))) : s;
}
